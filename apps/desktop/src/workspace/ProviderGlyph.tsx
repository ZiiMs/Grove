export interface ProviderGlyphProps {
  provider: string;
  /** Square size in px. The composer's inline picker uses the 14px default. */
  size?: number;
  className?: string;
}

/**
 * A provider's mark in the provider tint. A provider this build does not know falls back to the
 * two-letter monogram every other surface already uses, so a fifth vendor still renders.
 */
export function ProviderGlyph({ provider, size = 14, className }: ProviderGlyphProps) {
  const meta = providerMeta(provider);
  const glyph = GLYPHS[provider];

  if (!glyph) {
    return (
      <span
        className={["mark", "sm", "provider-mark", className ?? ""].filter(Boolean).join(" ")}
        style={{ ["--tint" as string]: meta.tint }}
        aria-hidden="true"
      >
        {meta.short}
      </span>
    );
  }

  return (
    <svg
      className={["provider-glyph", className ?? ""].filter(Boolean).join(" ")}
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="currentColor"
      style={{ color: meta.tint }}
      aria-hidden="true"
      focusable="false"
    >
      {glyph}
    </svg>
  );
}
